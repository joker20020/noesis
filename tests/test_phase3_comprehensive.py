async def test_3_sop_optimizer():
    print("\n[3] LLM SOP Optimizer")
    engine = AgentEngine(Config())
    await engine.init()

    reg = SkillRegistry(engine.neo4j, engine.config.skills_dir)
    await reg.register("test-opt", "test", "Optimization test")
    await reg.update_stage("test/test-opt", "SOP")

    # Write a SOP and usage data
    sop_dir = Path(engine.config.skills_dir) / "test" / "test-opt"
    sop_dir.mkdir(parents=True, exist_ok=True)
    (sop_dir / "SKILL.md").write_text("""---
name: test-opt
stage: "SOP"
---
# Test Opt
## Steps
1. Run file_read
2. Run code_run
""")

    # Create execution traces for the optimizer to analyze
    sid = 'opt-sess-2'
    await engine.neo4j.run(f"MERGE (s:Session {{session_id: '{sid}'}}) ON CREATE SET s.type='main', s.status='completed', s.created_at=datetime()")
    await engine.neo4j.run(f"MATCH (s:Session {{session_id: '{sid}'}}), (sk:Skill {{skill_id: 'test/test-opt'}}) MERGE (s)-[:USED_SKILL]->(sk)")
    await engine.neo4j.run(f"MATCH (s:Session {{session_id: '{sid}'}}) MERGE (s)-[:HAS_STEP]->(:ExecutionStep {{id: 'opt-step-0', name: 'file_read', role: 'system', step_index: 0, content: '[{{\"type\": \"tool_result\", \"name\": \"file_read\", \"output\": \"ok\"}}]', timestamp: datetime()}})")
    for i, tool in enumerate(["code_run", "memory_search"], start=1):
        await engine.neo4j.run(f"MATCH (prev:ExecutionStep {{id: 'opt-step-{i-1}'}}) MERGE (prev)-[:NEXT]->(:ExecutionStep {{id: 'opt-step-{i}', name: '{tool}', role: 'system', step_index: {i}, content: '[{{\"type\": \"tool_result\", \"name\": \"{tool}\", \"output\": \"ok\"}}]', timestamp: datetime()}})")


    llm = _FakeLLM()
    llm.next_response = LlmResponse(content=json.dumps({
        "suggestions": ["Add 'memory_search' step before file_read"],
        "variant_detected": True,
        "variant_description": "Some executions skip code_run and use web_scan instead",
        "recommended_updates": "Add conditional: if web data, use web_scan instead of file_read",
    }))

    opt = SopOptimizer(engine.neo4j, llm)
    result = await opt.optimize("test/test-opt")
    check("optimizer returns result", result is not None)
    if result:
        check("has suggestions", len(result["suggestions"]) > 0, str(result["suggestions"]))
        check("variant detected", result["variant_detected"])

    # Test heuristic fallback (no LLM)
    opt2 = SopOptimizer(engine.neo4j, None)
    result2 = await opt2.optimize("test/test-opt")
    check("heuristic fallback works", result2 is not None)

    # Cleanup
    await engine.neo4j.run("MATCH (s:Skill {skill_id: 'test/test-opt'}) DETACH DELETE s")
    await engine.neo4j.run("MATCH (s:Session {session_id: 'opt-sess-2'}) DETACH DELETE s")
    await engine.neo4j.run("MATCH (c:SkillCategory {name: 'test'}) DETACH DELETE c")
    shutil.rmtree(Path(engine.config.skills_dir) / "test", ignore_errors=True)
    await engine.close()


