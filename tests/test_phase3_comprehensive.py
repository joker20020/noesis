# ====== Test DTO for fake LLM ======
from llm.base import LlmClient, LlmResponse, Message, ToolCall as LlmTC


class _FakeLLM(LlmClient):
    """Simulate LLM responses for testing."""
    def __init__(self):
        self.calls = []
        self.next_response = LlmResponse(content="{}")

    async def chat(self, messages, tools=None):
        self.calls.append(messages[0].content[:80] if messages else "")
        return self.next_response


async def test_1_entity_extractor():
    print("\n[1] LLM Entity Extractor")
    engine = AgentEngine(Config())
    await engine.init()

    llm = _FakeLLM()
    llm.next_response = LlmResponse(content=json.dumps({
        "entities": [
            {"entity_id": "ent_svc_db", "entity_type": "Service", "name": "PostgreSQL",
             "content": "Production database on 10.0.1.50:5432", "properties": {"host": "10.0.1.50", "port": 5432}},
            {"entity_id": "ent_person_alice", "entity_type": "Person", "name": "Alice",
             "content": "Database administrator", "properties": {"email": "alice@example.com"}},
        ],
        "relations": [
            {"from": "ent_person_alice", "type": "MANAGES", "to": "ent_svc_db"},
        ],
    }))

    # Create a completed distillation request
    await engine.neo4j.run("""CREATE (d:DistillationRequest {
        session_id: 'extract_test', reason: 'subgoal_completed',
        summary: 'Discovered PostgreSQL database at 10.0.1.50:5432 managed by Alice',
        status: 'completed', processed_at: datetime()})""")

    ex = EntityExtractor(engine.neo4j, llm)
    await ex.extract_recent(lookback_minutes=1440)

    # Verify entities created
    for eid in ["ent_svc_db", "ent_person_alice"]:
        r = await engine.neo4j.run(f"MATCH (e:Entity {{entity_id: '{eid}'}}) RETURN e")
        check(f"Entity {eid} created", len(r) > 0, f"found={len(r)}")

    # Verify relation
    r = await engine.neo4j.run(
        "MATCH (a:Entity {entity_id: 'ent_person_alice'})-[r:MANAGES]->(b:Entity {entity_id: 'ent_svc_db'}) RETURN r")
    check("Relation MANAGES created", len(r) > 0)

    check("LLM called", len(llm.calls) == 1, f"calls={len(llm.calls)}")

    # Cleanup
    await engine.neo4j.run("MATCH (d:DistillationRequest {session_id: 'extract_test'}) DETACH DELETE d")
    await engine.neo4j.run("MATCH (e:Entity) WHERE e.entity_id IN ['ent_svc_db', 'ent_person_alice'] DETACH DELETE e")
    await engine.close()


