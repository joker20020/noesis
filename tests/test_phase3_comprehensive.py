async def test_5_four_d_scoring():
    print("\n[5] 4D Skill Scoring")
    engine = AgentEngine(Config())
    await engine.init()

    reg = SkillRegistry(engine.neo4j, engine.config.skills_dir)
    cats = ["web_automation", "data_processing", "web_automation", "ops", "web_automation"]
    for i, cat in enumerate(cats):
        await reg.register(f"score-s{i}", cat, f"Test skill {i}")
        # Vary usage
        await engine.neo4j.run(
            f"MATCH (s:Skill {{skill_id: '{cat}/score-s{i}'}}) SET s.usage_count = {i * 5}, s.activation = {1.0 - i * 0.1}")

    scorer = SkillScorer(engine.neo4j)
    results = await scorer.score_all()
    check("scoring produces results", len(results) >= 3, f"count={len(results)}")

    # Find top skill
    if results:
        top = results[0]
        check("score is positive", top["score"] > 0, str(top["score"]))
        check("has B/D/U/I dimensions", all(k in top["dimensions"] for k in ["B", "D", "U", "I"]),
              str(top["dimensions"]))
        print(f"    Top skill: {top['skill_id']} (score: {top['score']})")
        print(f"    Dimensions: {top['dimensions']}")

    # Weight adaptation
    if results:
        old_w = dict(scorer.weights)
        await scorer.adapt_weights({"score": 9.0, "dimensions": {"B": 8.0, "D": 2.0, "U": 1.0, "I": 0.0}}, actual_usage=0)
        check("weights changed", scorer.weights != old_w, f"{old_w} -> {scorer.weights}")

    # Cleanup
    for i, cat in enumerate(cats):
        await engine.neo4j.run(f"MATCH (s:Skill {{skill_id: '{cat}/score-s{i}'}}) DETACH DELETE s")
    for cat in set(cats):
        await engine.neo4j.run(f"MATCH (c:SkillCategory {{name: '{cat}'}}) DETACH DELETE c")
    await engine.close()


async def test_6_memory_lifecycle():
    print("\n[6] Memory Lifecycle")
    engine = AgentEngine(Config())
    await engine.init()

    lc = MemoryLifecycle(engine.neo4j)
    stats = await lc.get_stats()
    check("stats has skills", "skills" in stats, str(stats))
    check("stats has entities", "entities" in stats)
    check("stats has patterns", "patterns" in stats)

    # Create a test entity and test decay
    await engine.neo4j.run(
        """MERGE (e:Entity {entity_id: 'lifecycle-test'})
           SET e.entity_type = 'Test', e.name = 'LC', e.content = 'test',
               e.properties = '{}', e.activation = 0.5, e.source = 'test',
               e.created_at = datetime() - duration({days: 30})""")
    await lc.decay_all(days_threshold=7, rate=0.5)
    r = await engine.neo4j.run("MATCH (e:Entity {entity_id: 'lifecycle-test'}) RETURN e.activation AS a")
    check("entity decayed", r[0]["a"] < 0.5, f"activation={r[0]['a']}")

    await lc.consolidate_entity("lifecycle-test", boost=0.5)
    r = await engine.neo4j.run("MATCH (e:Entity {entity_id: 'lifecycle-test'}) RETURN e.activation AS a")
    check("entity consolidated", r[0]["a"] > 0.3, f"activation={r[0]['a']}")

    await engine.neo4j.run("MATCH (e:Entity {entity_id: 'lifecycle-test'}) DETACH DELETE e")
    await engine.close()


